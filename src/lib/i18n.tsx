export const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = {
  vi,
  en,
  zh,
};

type Params = Record<string, string | number>;

function interpolate(template: string, params?: Params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

function readStoredLanguage(): Language {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "vi" || saved === "en" || saved === "zh") return saved;
  } catch {
    /* storage unavailable */
  }
  return "vi";
}

/** Translate outside React (imperative helpers such as the browser demo). */
export function translate(key: TranslationKey, params?: Params): string {
  const dictionary = DICTIONARIES[readStoredLanguage()];
  return interpolate(dictionary[key] ?? key, params);
}

type I18nValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, params?: Params) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(readStoredLanguage);
  // A ref keeps `t` stable, so callbacks that depend on it never re-subscribe.
  const languageRef = useRef(language);
  languageRef.current = language;

  const t = useCallback((key: TranslationKey, params?: Params) => {
    const dictionary = DICTIONARIES[languageRef.current];
    return interpolate(dictionary[key] ?? key, params);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      /* storage unavailable */
    }
  }, [language]);

  const value = useMemo<I18nValue>(
    () => ({ language, setLanguage, t }),
    [language, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside <I18nProvider>");
  return value;
}
